"""
Build a single self-contained marimo notebook with the whole package inlined.

The output needs only `marimo` and `anywidget` (both on PyPI), so it runs
anywhere a notebook can install public packages — e.g. molab — without
access to this (private) repository.

    python scripts/build_standalone.py            # writes demo_standalone.py

Do not edit demo_standalone.py by hand; rebuild it. A test checks it is in
sync with the package.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
PKG = ROOT / "multilevel_table"
MODULES = ["header", "spans", "fields", "examples", "widget"]   # dependency order
OUT = ROOT / "demo_standalone.py"

_REL_IMPORT = re.compile(r"^from \.\w+ import (\([^)]*\)|[^\n]*)\n", re.M)
_FUTURE = re.compile(r"^from __future__ import annotations\n", re.M)


def combined_source() -> str:
    parts = ["from __future__ import annotations\n"]
    for name in MODULES:
        src = (PKG / f"{name}.py").read_text()
        src = _FUTURE.sub("", src)
        src = _REL_IMPORT.sub("", src)
        parts.append(f"\n# {'=' * 70}\n# multilevel_table/{name}.py\n# {'=' * 70}\n{src}")
    src = "".join(parts)

    # The widget reads its front end from files; inline them instead.
    js = (PKG / "static" / "widget.js").read_text()
    css = (PKG / "static" / "widget.css").read_text()
    src = re.sub(r"^_STATIC = .*\n", "", src, flags=re.M)
    # Function replacements: a string replacement would re-interpret the
    # backslash escapes inside repr() and break the literal.
    src, n_esm = re.subn(r'_esm = _STATIC / "widget\.js"', lambda _: f"_esm = {js!r}", src)
    src, n_css = re.subn(r'_css = _STATIC / "widget\.css"', lambda _: f"_css = {css!r}", src)
    if (n_esm, n_css) != (1, 1):
        sys.exit("build_standalone: could not find the _esm/_css lines in widget.py")
    return src


NOTEBOOK = '''# /// script
# requires-python = ">=3.11"
# dependencies = ["marimo", "anywidget"]
# ///
#
# GENERATED by scripts/build_standalone.py from the multilevel_table package.
# Do not edit by hand. Self-contained: needs only marimo + anywidget.

import marimo

__generated_with = "0.18.4"
app = marimo.App(width="full")


@app.cell(hide_code=True)
def _():
    # The multilevel_table package, inlined. Collapse this cell and ignore it.
    import sys as _sys
    import types as _types

    _SOURCE = __SOURCE__
    _mod = _types.ModuleType("multilevel_table")
    _sys.modules["multilevel_table"] = _mod
    exec(compile(_SOURCE, "multilevel_table (inlined)", "exec"), _mod.__dict__)

    H = _mod.H
    MultilevelTable = _mod.MultilevelTable
    Field = _mod.Field
    build_forest = _mod.build_forest
    example_headers = _mod.example_headers
    example_calculate = _mod.example_calculate
    return H, MultilevelTable, Field, build_forest, example_calculate, example_headers


@app.cell
def _():
    import marimo as mo

    mo.md("""
    # MultilevelTable

    Click a column header marked **\\u2013** to merge its children into it, or **+** to split it
    again. Merged columns are recalculated. Click a tile to select it.
    """)
    return (mo,)


@app.cell
def _(MultilevelTable, example_calculate, example_headers, mo):
    # Replace example_headers / example_calculate with your own:
    #   row_headers, col_headers = H(...), H(...)
    #   def calculate(row_path, col_path) -> "<svg ...>...</svg>" | number | text
    row_headers, col_headers = example_headers()
    table = MultilevelTable(row_headers, col_headers, example_calculate, cell_width=96, cell_height=48)
    widget = mo.ui.anywidget(table)
    widget
    return (widget,)


@app.cell
def _(mo, widget):
    _sel = widget.value["selected"]
    mo.md(f"""
    **Merged columns:** {", ".join(widget.value["col_merged"]) or "none"}

    **Grid:** {len(widget.value["row_paths"])} rows \\u00d7 {len(widget.value["col_paths"])} columns

    **Selected cell:** {" \\u203a ".join(_sel["row"]) + "  \\u00d7  " + " \\u203a ".join(_sel["col"]) if _sel else "none"}
    """)
    return


if __name__ == "__main__":
    app.run()
'''


def build() -> str:
    return NOTEBOOK.replace("__SOURCE__", repr(combined_source()))


def main() -> None:
    OUT.write_text(build())
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
